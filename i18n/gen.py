"""Generates translation tables for every part of PhoneCam from i18n/*_strings.py."""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
sys.path.insert(0, here)

def c_lit(s):
    out = []
    for ch in s:
        if ch == '\\': out.append('\\\\')
        elif ch == '"': out.append('\\"')
        elif ch == '\n': out.append('\\n')
        elif ch == '\t': out.append('\\t')
        elif ch == '\r': out.append('\\r')
        else: out.append(ch)
    return 'u8"' + ''.join(out) + '"'

def gen_pc():
    from pc_strings import T
    lines = ['// Generated by i18n/gen.py from i18n/pc_strings.py - do not edit.']
    for ru, (en, uk) in T.items():
        lines.append('{(const char*)%s, (const char*)%s, (const char*)%s},' % (c_lit(ru), c_lit(en), c_lit(uk)))
    open(os.path.join(root, 'pc/core/i18n_table.inc'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('pc', len(T))

def gen_android():
    p = os.path.join(here, 'android_strings.py')
    if not os.path.exists(p): return
    from android_strings import T
    j = lambda s: json.dumps(s, ensure_ascii=False)
    body = '\n'.join('        m.put(%s, new String[] {%s, %s});' % (j(ru), j(en), j(uk)) for ru, (en, uk) in T.items())
    src = '''// Generated by i18n/gen.py from i18n/android_strings.py - do not edit.
package com.phonecam.app;

import java.util.HashMap;

final class Strings {
    static HashMap<String, String[]> load() {
        HashMap<String, String[]> m = new HashMap<>();
%s
        return m;
    }
}
''' % body
    open(os.path.join(root, 'android/src/com/phonecam/app/Strings.java'), 'w', encoding='utf-8').write(src)
    print('android', len(T))

def gen_web():
    from web_strings import T
    d = {ru: [en, uk] for ru, (en, uk) in T.items() if not ru.startswith('BOT_')}
    p = os.path.join(root, 'web/phone.html')
    s = open(p, encoding='utf-8').read()
    a = s.index('/*I18N*/'); b = s.index('/*I18N_END*/')
    s = s[:a] + '/*I18N*/' + json.dumps(d, ensure_ascii=False) + s[b:]
    open(p, 'w', encoding='utf-8').write(s)
    print('web', len(d))

gen_pc(); gen_android(); gen_web()
